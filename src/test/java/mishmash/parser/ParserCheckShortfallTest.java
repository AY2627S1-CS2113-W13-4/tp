package mishmash.parser;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import java.util.Random;

import org.junit.jupiter.api.Test;

import mishmash.command.CheckShortfallCommand;
import mishmash.command.Command;
import mishmash.exception.MishMashException;
import mishmash.logic.MealPlanGenerator;
import mishmash.model.ActiveMealPlan;
import mishmash.model.DayPlan;
import mishmash.model.GroceryItem;
import mishmash.model.MealPlan;
import mishmash.model.Recipe;
import mishmash.model.RecipeBook;
import mishmash.testutil.TestRecipes;
import mishmash.ui.MealPlanViewer.MealSummary;

//@@author Rixte
/**
 * Checks target parsing, recovery, and integration with the plan generated by the shared parser.
 */
class ParserCheckShortfallTest {
    @Test
    void parseCommand_singleTargetOfAnyKind_isAccepted() throws MishMashException {
        Parser parser = new Parser();
        for (String arguments : new String[]{"cal/2000", "p/100", "c/250", "f/60"}) {
            assertInstanceOf(CheckShortfallCommand.class,
                    parser.parseCommand("check-shortfall " + arguments));
        }
    }

    @Test
    void parseCommand_invalidTargets_reportsUsageAndRecovers() throws MishMashException {
        Parser parser = new Parser();
        String[] invalidArguments = {"", " ", "cal/", "cal/0", "p/-1", "c/+1", "f/1.5", "cal/abc",
            "cal/2147483648", "cal/2000 cal/2100", "p/100 p/120", "d/1", "CAL/2000",
            "cal/2000 extra", "cal/2000/p/100", "cal/ 2000", "2000"};
        for (String arguments : invalidArguments) {
            MishMashException error = assertThrows(MishMashException.class,
                    () -> parser.parseCommand("check-shortfall " + arguments), arguments);
            assertTrue(error.getMessage().endsWith(CheckShortfallCommand.USAGE), arguments);
            assertInstanceOf(IllegalArgumentException.class, error.getCause());
        }
        assertInstanceOf(CheckShortfallCommand.class, parser.parseCommand("check-shortfall cal/2000"));
    }

    @Test
    void parseCommand_missingValues_preservesSpecificMessageCauseAndUsage() {
        Parser parser = new Parser();
        for (String prefix : List.of("cal", "p", "c", "f")) {
            MishMashException error = assertThrows(MishMashException.class,
                    () -> parser.parseCommand("check-shortfall " + prefix + "/"));

            assertEquals("Missing value after " + prefix + "/." + System.lineSeparator()
                    + CheckShortfallCommand.USAGE, error.getMessage());
            assertInstanceOf(IllegalArgumentException.class, error.getCause());
            assertEquals("Missing value after " + prefix + "/.", error.getCause().getMessage());
        }
    }

    @Test
    void parseCommand_rejectedTargets_leaveExistingPlanGroceriesAndRecipesUnchanged() throws MishMashException {
        ActiveMealPlan activePlan = new ActiveMealPlan();
        Parser parser = new Parser(new MealPlanGenerator(new Random(42)), activePlan);
        RecipeBook recipes = new RecipeBook();
        Recipe recipe = TestRecipes.recipe("Stored", 1800, 80, 200, 50);
        recipes.add(recipe);
        MealPlan plan = new MealPlan(List.of(new DayPlan(List.of(recipe))));
        activePlan.set(plan);
        activePlan.setGroceryList(recipe.getIngredients());
        List<GroceryItem> groceries = activePlan.getGroceryList().orElseThrow();
        List<Recipe> originalRecipes = recipes.getRecipes();
        List<List<MealSummary>> originalMeals = plan.toMealSummaries();

        for (String arguments : List.of("cal/", "p/0", "c/2147483648", "f/1 f/2", "cal/2000 unknown/1")) {
            assertThrows(MishMashException.class, () -> parser.parseCommand("check-shortfall " + arguments));
            assertSame(plan, activePlan.get().orElseThrow());
            assertEquals(originalMeals, plan.toMealSummaries());
            assertSame(groceries, activePlan.getGroceryList().orElseThrow());
            assertEquals(originalRecipes, recipes.getRecipes());
        }
        String result = parser.parseCommand("check-shortfall p/100").execute(recipes);
        assertTrue(result.contains("Protein: 80/100 g (short by 20 g)."));
        assertFalse(result.contains("Calories:"));
        assertSame(groceries, activePlan.getGroceryList().orElseThrow());
    }

    @Test
    void parseCommand_reorderedTargets_printsDeficitsInCanonicalNutrientOrder() throws MishMashException {
        ActiveMealPlan activePlan = new ActiveMealPlan();
        activePlan.set(new MealPlan(List.of(new DayPlan(List.of(TestRecipes.recipe("Meal", 1800, 80, 200, 50))))));
        Parser parser = new Parser(new MealPlanGenerator(new Random(42)), activePlan);

        String result = parser.parseCommand("check-shortfall f/60 c/250 p/100 cal/2000").execute(new RecipeBook());

        assertEquals(String.join(System.lineSeparator(),
                "Daily nutrition shortfalls (compared with the supplied targets):", "Day 1:",
                "- Calories: 1800/2000 kcal (short by 200 kcal).",
                "- Protein: 80/100 g (short by 20 g).",
                "- Carbs: 200/250 g (short by 50 g).",
                "- Fats: 50/60 g (short by 10 g)."), result);
    }

    @Test
    void parseCommand_checksPlanAfterRecipesAreDeletedFromBook() throws MishMashException {
        Parser parser = new Parser();
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        parser.parseCommand("generate-plan d/1").execute(recipes);
        parser.parseCommand("generate-list").execute(recipes);
        String originalGroceries = parser.parseCommand("view-list").execute(recipes);
        String originalPlan = parser.parseCommand("view-plan").execute(recipes);
        Command check = parser.parseCommand("check-shortfall cal/2000");
        while (recipes.size() > 0) {
            recipes.remove(0);
        }

        String result = check.execute(recipes);

        assertTrue(result.contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
        assertEquals(originalPlan, parser.parseCommand("view-plan").execute(recipes));
        assertEquals(originalGroceries, parser.parseCommand("view-list").execute(recipes));
        assertEquals(0, recipes.size());
    }

    @Test
    void parseCommand_suppliedTargetsOverrideGenerationTargetsWithoutSavingThem() throws MishMashException {
        Parser parser = new Parser();
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        parser.parseCommand("generate-plan d/1 cal/2000").execute(recipes);

        String result = parser.parseCommand("check-shortfall cal/1800").execute(recipes);

        assertTrue(result.contains("Day 1: No shortfalls for the supplied targets."));
        assertThrows(MishMashException.class, () -> parser.parseCommand("check-shortfall"));
        assertTrue(parser.parseCommand("check-shortfall cal/2000").execute(recipes)
                .contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
    }

    @Test
    void parseCommand_beforePlanGeneration_readsGeneratedPlanWithoutChangingIt() throws MishMashException {
        ActiveMealPlan activePlan = new ActiveMealPlan();
        Parser parser = new Parser(new MealPlanGenerator(new Random(42)), activePlan);
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        Command check = parser.parseCommand("check-shortfall cal/2000 p/100 c/200 f/60");
        assertTrue(activePlan.get().isEmpty());

        parser.parseCommand("generate-plan d/2").execute(recipes);
        MealPlan plan = activePlan.get().orElseThrow();
        parser.parseCommand("generate-list").execute(recipes);
        String result = check.execute(recipes);

        assertTrue(result.contains("Day 1:"));
        assertTrue(result.contains("Day 2:"));
        assertTrue(result.contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
        assertTrue(result.contains("Protein: 90/100 g (short by 10 g)."));
        assertTrue(result.contains("Carbs: 150/200 g (short by 50 g)."));
        assertTrue(result.contains("Fats: 30/60 g (short by 30 g)."));
        assertSame(plan, activePlan.get().orElseThrow());
        assertTrue(activePlan.getGroceryList().isPresent());
        assertEquals(3, recipes.size());
    }

    @Test
    void parseCommand_defaultParser_connectsToGeneratedPlanAndPreservesItAfterFailedGeneration()
            throws MishMashException {
        Parser parser = new Parser();
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        parser.parseCommand("generate-plan d/1").execute(recipes);
        Command check = parser.parseCommand(" \tcheck-shortfall\t cal/02000 p/0100 \t");
        String originalResult = check.execute(recipes);

        assertThrows(MishMashException.class,
                () -> parser.parseCommand("generate-plan d/2 cal/1").execute(recipes));

        assertTrue(originalResult.contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
        assertTrue(originalResult.contains("Protein: 90/100 g (short by 10 g)."));
        assertEquals(originalResult, check.execute(recipes));
    }
}
