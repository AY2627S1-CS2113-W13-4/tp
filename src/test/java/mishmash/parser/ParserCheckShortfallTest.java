package mishmash.parser;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.Random;

import org.junit.jupiter.api.Test;

import mishmash.command.CheckShortfallCommand;
import mishmash.command.Command;
import mishmash.exception.MishMashException;
import mishmash.logic.MealPlanGenerator;
import mishmash.model.ActiveMealPlan;
import mishmash.model.MealPlan;
import mishmash.model.RecipeBook;
import mishmash.testutil.TestRecipes;

/** Checks target parsing, recovery, and integration with the plan generated by the shared parser. */
class ParserCheckShortfallTest {
    @Test
    void parseCommand_singleTargetOfAnyKind_isAccepted() throws MishMashException {
        Parser parser = new Parser();
        for (String arguments : new String[]{"cal/2000", "p/100", "c/250", "f/60"}) {
            assertInstanceOf(CheckShortfallCommand.class, parser.parseCommand("check-shortfall " + arguments));
        }
    }

    @Test
    void parseCommand_invalidTargets_reportsUsageAndRecovers() throws MishMashException {
        Parser parser = new Parser();
        String[] invalid = {"", " ", "cal/", "cal/0", "p/-1", "c/+1", "f/1.5", "cal/abc",
            "cal/2147483648", "cal/2000 cal/2100", "p/100 p/120", "d/1", "CAL/2000",
            "cal/2000 extra", "cal/2000/p/100", "cal/ 2000", "2000"};
        for (String arguments : invalid) {
            MishMashException error = assertThrows(MishMashException.class,
                    () -> parser.parseCommand("check-shortfall " + arguments), arguments);
            assertTrue(error.getMessage().endsWith(CheckShortfallCommand.USAGE), arguments);
            assertInstanceOf(IllegalArgumentException.class, error.getCause());
        }
        assertInstanceOf(CheckShortfallCommand.class, parser.parseCommand("check-shortfall cal/2000"));
    }

    @Test
    void parseCommand_beforePlanGeneration_readsGeneratedPlanWithoutChangingIt() throws MishMashException {
        ActiveMealPlan activePlan = new ActiveMealPlan();
        Parser parser = new Parser(new MealPlanGenerator(new Random(42)), activePlan);
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        Command check = parser.parseCommand("check-shortfall cal/2000 p/100 c/200 f/60");
        assertFalse(activePlan.get().isPresent());

        parser.parseCommand("generate-plan d/2").execute(recipes);
        MealPlan plan = activePlan.get().orElseThrow();
        parser.parseCommand("generate-list").execute(recipes);
        String result = check.execute(recipes);

        assertTrue(result.contains("Day 1:"));
        assertTrue(result.contains("Day 2:"));
        assertTrue(result.contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
        assertTrue(result.contains("Protein: 90/100 g (short by 10 g)."));
        assertTrue(result.contains("Carbs: 150/200 g (short by 50 g)."));
        assertTrue(result.contains("Fats: 30/60 g (short by 30 g)."));
        assertSame(plan, activePlan.get().orElseThrow());
        assertTrue(activePlan.getGroceryList().isPresent());
        assertEquals(3, recipes.size());
    }

    @Test
    void parseCommand_defaultParser_connectsToGeneratedPlanAndPreservesItAfterFailedGeneration()
            throws MishMashException {
        Parser parser = new Parser();
        RecipeBook recipes = new RecipeBook();
        recipes.add(TestRecipes.recipe("A", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("B", 600, 30, 50, 10));
        recipes.add(TestRecipes.recipe("C", 600, 30, 50, 10));
        parser.parseCommand("generate-plan d/1").execute(recipes);
        Command check = parser.parseCommand(" \tcheck-shortfall\t cal/02000 p/0100 \t");
        String originalResult = check.execute(recipes);

        assertThrows(MishMashException.class,
                () -> parser.parseCommand("generate-plan d/2 cal/1").execute(recipes));

        assertTrue(originalResult.contains("Calories: 1800/2000 kcal (short by 200 kcal)."));
        assertTrue(originalResult.contains("Protein: 90/100 g (short by 10 g)."));
        assertEquals(originalResult, check.execute(recipes));
    }
}
